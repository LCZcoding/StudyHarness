-- ============================================================
-- ai-agent-study · 数据库建表脚本
-- 目标库：ai_agent_study（PostgreSQL 16）
-- 验证环境：PostgreSQL 16.15，已实测通过（FK / CHECK 约束生效）
--
-- 执行顺序不可颠倒（外键依赖）：t_user -> t_conversation -> t_message
-- 本脚本幂等：可重复执行；但注意 CREATE TABLE IF NOT EXISTS 只跳过已存在的表，
-- 不会比对定义差异（改了字段记得手动 ALTER，别指望重跑脚本生效）。
--
-- 建库本身不在本脚本内（CREATE DATABASE 不能在事务块中执行，且需先连到默认库）：
--   连到 postgres 库执行：CREATE DATABASE ai_agent_study;
--
-- 本库同时承担 pgvector 向量存储（spring-ai-pgvector-store，表名 vector_store）。
-- 若目标机器需要启用向量能力，另行执行：
--   CREATE EXTENSION IF NOT EXISTS vector;
-- ============================================================

CREATE TABLE IF NOT EXISTS t_user (
    id            UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS t_conversation (
    id         UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id    UUID         NOT NULL REFERENCES t_user(id),
    mode       VARCHAR(20)  NOT NULL CHECK (mode IN ('SELF_TEST','FREE_CHAT','REVIEW','PRACTICE')),
    title      VARCHAR(50),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS t_message (
    id              BIGINT       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    conversation_id UUID         NOT NULL REFERENCES t_conversation(id),
    role            VARCHAR(20)  NOT NULL CHECK (role IN ('USER','ASSISTANT','TOOL')),
    type            VARCHAR(20)  NOT NULL CHECK (type IN ('QUESTION','ANSWER','FEEDBACK','CHAT')),
    content         TEXT         NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
